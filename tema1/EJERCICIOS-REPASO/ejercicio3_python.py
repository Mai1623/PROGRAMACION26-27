#Realizar cálculos aritméticos simples entre variables numéricas.

# Guardamos el primer número en una variable
numero1 = 10
# Guardamos el segundo número en otra variable
numero2 = 5
# Sumamos los dos números
suma = numero1 + numero2
# Restamos el segundo número al primero
resta = numero1 - numero2
# Multiplicamos los dos números
multiplicacion = numero1 * numero2
# Dividimos el primer número entre el segundo
division = numero1 / numero2
# Mostramos el resultado de la suma
print("Suma:", suma)
# Mostramos el resultado de la resta
print("Resta:", resta)
# Mostramos el resultado de la multiplicación
print("Multiplicación:", multiplicacion)
# Mostramos el resultado de la división
print("División:", division)
